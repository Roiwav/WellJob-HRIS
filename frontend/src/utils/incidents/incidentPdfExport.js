import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

function clean(value, fallback = "-") {
  const normalized = String(
    value ?? ""
  ).trim();

  return normalized || fallback;
}

function getIncidentDate(incident) {
  const value =
    incident?.date ||
    incident?.incidentDate ||
    incident?.incident_date ||
    incident?.reportedAt ||
    incident?.reported_at ||
    incident?.createdAt ||
    incident?.created_at;

  if (!value) {
    return "-";
  }

  const parsed = new Date(value);

  if (Number.isNaN(parsed.getTime())) {
    return clean(value);
  }

  return parsed.toLocaleDateString(
    "en-PH",
    {
      year: "numeric",
      month: "short",
      day: "2-digit",
    }
  );
}

function formatIncidentCode(id) {
  const value = clean(id, "");

  if (!value) {
    return "-";
  }

  if (value.startsWith("INC-")) {
    return value;
  }

  const numeric = Number(value);

  return Number.isFinite(numeric)
    ? `INC-${String(numeric).padStart(4, "0")}`
    : value;
}

function countBy(
  incidents,
  getValue,
  fallback
) {
  return incidents.reduce(
    (summary, incident) => {
      const label = clean(
        getValue(incident),
        fallback
      );

      summary[label] =
        (summary[label] || 0) + 1;

      return summary;
    },
    {}
  );
}

function toSummaryRows(summary, total) {
  const entries = Object.entries(
    summary
  ).sort(
    (first, second) =>
      second[1] - first[1]
  );

  if (entries.length === 0) {
    return [["No records", 0, "0%"]];
  }

  return entries.map(
    ([label, count]) => [
      label,
      count,
      total > 0
        ? `${Math.round(
            (count / total) * 100
          )}%`
        : "0%",
    ]
  );
}

function addSectionTitle(doc, title, y) {
  doc.setFontSize(11);
  doc.setFont(undefined, "bold");
  doc.setTextColor(15, 23, 42);
  doc.text(title, 14, y);
  doc.setFont(undefined, "normal");
}

function getNextY(doc, spacing = 8) {
  return (
    (doc.lastAutoTable?.finalY || 36) +
    spacing
  );
}

export function exportIncidentReportPDF({
  incidents = [],
  user,
  scopeCompany = "",
  filters = {},
}) {
  const safeIncidents = Array.isArray(
    incidents
  )
    ? incidents
    : [];

  const doc = new jsPDF({
    orientation: "landscape",
    unit: "mm",
    format: "a4",
  });

  const total = safeIncidents.length;
  const generatedBy = clean(
    user?.full_name ||
      user?.fullName ||
      user?.name ||
      user?.username,
    "System User"
  );
  const reportScope = scopeCompany
    ? `Assigned company: ${scopeCompany}`
    : "All authorized companies";
  const activeFilters = [
    filters.caseTab &&
    filters.caseTab !== "ALL"
      ? `Case group: ${filters.caseTab}`
      : "",
    filters.status &&
    filters.status !== "ALL"
      ? `Status: ${filters.status}`
      : "",
    filters.severity &&
    filters.severity !== "ALL"
      ? `Severity: ${filters.severity}`
      : "",
    filters.search
      ? `Search: ${filters.search}`
      : "",
  ].filter(Boolean);

  doc.setFontSize(17);
  doc.setFont(undefined, "bold");
  doc.setTextColor(30, 41, 59);
  doc.text(
    "Welljob Incident Records Report",
    14,
    16
  );

  doc.setFontSize(9);
  doc.setFont(undefined, "normal");
  doc.setTextColor(71, 85, 105);
  doc.text(
    `Generated by: ${generatedBy}`,
    14,
    23
  );
  doc.text(
    `Generated on: ${new Date().toLocaleString("en-PH")}`,
    14,
    28
  );
  doc.text(reportScope, 145, 23);
  doc.text(
    activeFilters.length > 0
      ? activeFilters.join(" | ")
      : "Filters: All incident records",
    145,
    28,
    {
      maxWidth: 135,
    }
  );

  addSectionTitle(
    doc,
    "Report Summary",
    38
  );

  autoTable(doc, {
    startY: 42,
    head: [[
      "Total Records",
      "Active",
      "For Review",
      "Closed",
      "Critical",
    ]],
    body: [[
      total,
      safeIncidents.filter((incident) =>
        ["Open", "Investigating"].includes(
          clean(incident?.status)
        )
      ).length,
      safeIncidents.filter(
        (incident) =>
          clean(incident?.status) ===
          "For Review"
      ).length,
      safeIncidents.filter(
        (incident) =>
          clean(incident?.status) ===
          "Closed"
      ).length,
      safeIncidents.filter(
        (incident) =>
          clean(incident?.severity) ===
          "Critical"
      ).length,
    ]],
    theme: "grid",
    styles: {
      fontSize: 9,
      halign: "center",
    },
    headStyles: {
      fillColor: [79, 70, 229],
    },
  });

  const statusSummary = countBy(
    safeIncidents,
    (incident) => incident?.status,
    "Unspecified Status"
  );
  const severitySummary = countBy(
    safeIncidents,
    (incident) => incident?.severity,
    "Unspecified Severity"
  );
  const companySummary = countBy(
    safeIncidents,
    (incident) => incident?.company,
    "Unassigned Company"
  );

  addSectionTitle(
    doc,
    "Status Summary",
    getNextY(doc)
  );
  autoTable(doc, {
    startY: getNextY(doc, 4),
    head: [["Status", "Records", "Share"]],
    body: toSummaryRows(
      statusSummary,
      total
    ),
    theme: "striped",
    styles: { fontSize: 8 },
    headStyles: {
      fillColor: [14, 165, 233],
    },
    tableWidth: 82,
    margin: { left: 14 },
  });

  const summaryStartY =
    doc.lastAutoTable?.startY || 70;

  autoTable(doc, {
    startY: summaryStartY,
    head: [["Severity", "Records", "Share"]],
    body: toSummaryRows(
      severitySummary,
      total
    ),
    theme: "striped",
    styles: { fontSize: 8 },
    headStyles: {
      fillColor: [245, 158, 11],
    },
    tableWidth: 82,
    margin: { left: 107 },
  });

  autoTable(doc, {
    startY: summaryStartY,
    head: [["Company", "Records", "Share"]],
    body: toSummaryRows(
      companySummary,
      total
    ),
    theme: "striped",
    styles: { fontSize: 8 },
    headStyles: {
      fillColor: [16, 185, 129],
    },
    tableWidth: 82,
    margin: { left: 200 },
  });

  doc.addPage();
  addSectionTitle(
    doc,
    "Incident Records",
    14
  );

  autoTable(doc, {
    startY: 18,
    head: [[
      "Incident",
      "Date",
      "Employee",
      "Company",
      "Violation",
      "Severity",
      "Status",
      "Reported By",
    ]],
    body:
      safeIncidents.length > 0
        ? safeIncidents.map(
            (incident) => [
              formatIncidentCode(
                incident?.id
              ),
              getIncidentDate(
                incident
              ),
              clean(
                incident?.employee ||
                  incident?.employeeName ||
                  incident?.employee_name
              ),
              clean(
                incident?.company
              ),
              clean(
                incident?.violation ||
                  incident?.violationType ||
                  incident?.violation_type
              ),
              clean(
                incident?.severity
              ),
              clean(
                incident?.status
              ),
              clean(
                incident?.reportedBy ||
                  incident?.reportedByName ||
                  incident?.reported_by
              ),
            ]
          )
        : [[
            "-",
            "-",
            "No incident records matched the selected filters.",
            "-",
            "-",
            "-",
            "-",
            "-",
          ]],
    theme: "grid",
    styles: {
      fontSize: 7.5,
      cellPadding: 2.2,
      overflow: "linebreak",
      valign: "middle",
    },
    headStyles: {
      fillColor: [30, 41, 59],
      fontSize: 8,
    },
    columnStyles: {
      0: { cellWidth: 22 },
      1: { cellWidth: 24 },
      2: { cellWidth: 40 },
      3: { cellWidth: 38 },
      4: { cellWidth: 48 },
      5: { cellWidth: 24 },
      6: { cellWidth: 27 },
      7: { cellWidth: 38 },
    },
    didDrawPage: (data) => {
      const pageNumber =
        doc.internal.getNumberOfPages();
      const pageWidth =
        doc.internal.pageSize.getWidth();
      const pageHeight =
        doc.internal.pageSize.getHeight();

      doc.setFontSize(7);
      doc.setTextColor(100);
      doc.text(
        `Incident Records | Page ${pageNumber}`,
        pageWidth - 14,
        pageHeight - 7,
        { align: "right" }
      );

      if (data.pageNumber > 1) {
        doc.setFontSize(10);
        doc.setFont(undefined, "bold");
        doc.setTextColor(30, 41, 59);
        doc.text(
          "Welljob Incident Records Report",
          14,
          10
        );
      }
    },
  });

  const dateStamp = new Date()
    .toISOString()
    .slice(0, 10);

  doc.save(
    `Welljob_Incident_Records_${dateStamp}.pdf`
  );
}